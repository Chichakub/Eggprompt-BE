-- Run in Supabase SQL Editor only if daily_egg_logs does not exist.
-- Existing tables are preserved; this script does not alter their columns.
CREATE TABLE IF NOT EXISTS public.daily_egg_logs (
    egg_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    record_date DATE NOT NULL,
    flock_id INT NOT NULL,

    grade_jumbo_qty INT NOT NULL DEFAULT 0,
    grade_0_qty INT NOT NULL DEFAULT 0,
    grade_1_qty INT NOT NULL DEFAULT 0,
    grade_2_qty INT NOT NULL DEFAULT 0,
    grade_3_qty INT NOT NULL DEFAULT 0,
    grade_4_qty INT NOT NULL DEFAULT 0,
    grade_5_qty INT NOT NULL DEFAULT 0,

    defective_qty INT NOT NULL DEFAULT 0,

    saleable_egg_count INT GENERATED ALWAYS AS (
        grade_jumbo_qty
        + grade_0_qty
        + grade_1_qty
        + grade_2_qty
        + grade_3_qty
        + grade_4_qty
        + grade_5_qty
    ) STORED,

    total_egg_count INT GENERATED ALWAYS AS (
        grade_jumbo_qty
        + grade_0_qty
        + grade_1_qty
        + grade_2_qty
        + grade_3_qty
        + grade_4_qty
        + grade_5_qty
        + defective_qty
    ) STORED,

    total_tray_count DECIMAL(10,2) GENERATED ALWAYS AS (
        (
            grade_jumbo_qty
            + grade_0_qty
            + grade_1_qty
            + grade_2_qty
            + grade_3_qty
            + grade_4_qty
            + grade_5_qty
            + defective_qty
        ) / 30.0
    ) STORED,

    egg_lot_number VARCHAR(50) NULL,
    created_by_user_id INT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,

    CONSTRAINT chk_egg_grade_jumbo_qty
        CHECK (grade_jumbo_qty >= 0),

    CONSTRAINT chk_egg_grade_0_qty
        CHECK (grade_0_qty >= 0),

    CONSTRAINT chk_egg_grade_1_qty
        CHECK (grade_1_qty >= 0),

    CONSTRAINT chk_egg_grade_2_qty
        CHECK (grade_2_qty >= 0),

    CONSTRAINT chk_egg_grade_3_qty
        CHECK (grade_3_qty >= 0),

    CONSTRAINT chk_egg_grade_4_qty
        CHECK (grade_4_qty >= 0),

    CONSTRAINT chk_egg_grade_5_qty
        CHECK (grade_5_qty >= 0),

    CONSTRAINT chk_egg_defective_qty
        CHECK (defective_qty >= 0),

    CONSTRAINT fk_daily_egg_flock
        FOREIGN KEY (flock_id)
        REFERENCES flocks(flock_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_daily_egg_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT
);
